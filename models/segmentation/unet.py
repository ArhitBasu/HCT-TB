import torch
import torch.nn as nn
import torch.nn.functional as F

class DoubleConv(nn.Module):
    """(convolution => [BN] => ReLU) * 2"""
    def __init__(self, in_channels, out_channels, mid_channels=None):
        super().__init__()
        if not mid_channels:
            mid_channels = out_channels
        self.double_conv = nn.Sequential(
            nn.Conv2d(in_channels, mid_channels, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(mid_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(mid_channels, out_channels, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.double_conv(x)

class Down(nn.Module):
    """Downscaling with maxpool then double conv"""
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.maxpool_conv = nn.Sequential(
            nn.MaxPool2d(2),
            DoubleConv(in_channels, out_channels)
        )

    def forward(self, x):
        return self.maxpool_conv(x)

class Up(nn.Module):
    """Upscaling then double conv"""
    def __init__(self, in_channels, out_channels, bilinear=True):
        super().__init__()

        # if bilinear, use the normal convolutions to reduce the number of channels
        if bilinear:
            self.up = nn.Upsample(scale_factor=2, mode='bilinear', align_corners=True)
            self.conv = DoubleConv(in_channels, out_channels, in_channels // 2)
        else:
            self.up = nn.ConvTranspose2d(in_channels, in_channels // 2, kernel_size=2, stride=2)
            self.conv = DoubleConv(in_channels, out_channels)

    def forward(self, x1, x2):
        x1 = self.up(x1)
        # input is CHW
        diffY = x2.size()[2] - x1.size()[2]
        diffX = x2.size()[3] - x1.size()[3]

        x1 = F.pad(x1, [diffX // 2, diffX - diffX // 2,
                        diffY // 2, diffY - diffY // 2])
        x = torch.cat([x2, x1], dim=1)
        return self.conv(x)

class OutConv(nn.Module):
    def __init__(self, in_channels, out_channels):
        super(OutConv, self).__init__()
        self.conv = nn.Conv2d(in_channels, out_channels, kernel_size=1)

    def forward(self, x):
        return self.conv(x)

class UNetLungSegmentation(nn.Module):
    """
    U-Net for ROI Lung Segmentation.
    
    This acts as the preprocessing filter before classification. 
    It identifies the lung boundaries and generates a binary mask, 
    allowing us to mask out irrelevant background artifacts (bones, 
    hospital tags, pacemakers) that cause false correlations.
    """
    def __init__(self, n_channels=3, n_classes=1, bilinear=False):
        super(UNetLungSegmentation, self).__init__()
        self.n_channels = n_channels
        self.n_classes = n_classes
        self.bilinear = bilinear

        self.inc = DoubleConv(n_channels, 64)
        self.down1 = Down(64, 128)
        self.down2 = Down(128, 256)
        self.down3 = Down(256, 512)
        factor = 2 if bilinear else 1
        self.down4 = Down(512, 1024 // factor)
        
        self.up1 = Up(1024, 512 // factor, bilinear)
        self.up2 = Up(512, 256 // factor, bilinear)
        self.up3 = Up(256, 128 // factor, bilinear)
        self.up4 = Up(128, 64, bilinear)
        self.outc = OutConv(64, n_classes)

    def forward(self, x):
        """
        Forward pass for segmentation.
        
        Args:
            x (torch.Tensor): Original CXR image (B, 3, 224, 224)
            
        Returns:
            torch.Tensor: Lung mask logits (B, 1, 224, 224)
        """
        x1 = self.inc(x)
        x2 = self.down1(x1)
        x3 = self.down2(x2)
        x4 = self.down3(x3)
        x5 = self.down4(x4)
        
        x = self.up1(x5, x4)
        x = self.up2(x, x3)
        x = self.up3(x, x2)
        x = self.up4(x, x1)
        logits = self.outc(x)
        
        return logits

def apply_roi_mask(image: torch.Tensor, mask_logits: torch.Tensor) -> torch.Tensor:
    """
    Utility function to apply the U-Net mask to the original image.
    """
    probabilities = torch.sigmoid(mask_logits)
    binary_mask = (probabilities > 0.5).float()
    
    # Apply mask (broadcasting over the 3 color channels)
    return image * binary_mask

if __name__ == "__main__":
    model = UNetLungSegmentation(n_channels=3, n_classes=1)
    dummy_xray = torch.randn(2, 3, 224, 224)
    
    mask_logits = model(dummy_xray)
    roi_image = apply_roi_mask(dummy_xray, mask_logits)
    
    print(f"Original X-Ray Shape: {dummy_xray.shape}")
    print(f"U-Net Mask Logits Shape: {mask_logits.shape}")
    print(f"Masked ROI Image Shape: {roi_image.shape}")
